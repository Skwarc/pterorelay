def normalize_locale(value: object, fallback: str = "en") -> str:
    candidate = str(value or "").replace("_", "-").lower().split("-", 1)[0]
    return candidate if candidate in SUPPORTED_LOCALES else fallback


def translate(key: str, locale: object = "en", values: Mapping[str, object] | None = None) -> str:
    language = normalize_locale(locale)
    template = MESSAGES.get(language, {}).get(key) or MESSAGES["en"].get(key) or key
    return template.format_map(dict(values or {}))
